#!/usr/bin/env python3
"""Score the token/unigram test against the rule pre-registered at 6848d4c, and emit its table.

Written BEFORE any lextok receipt exists, so the scoring cannot be tuned to a result.
The rule, verbatim from the pre-registration:

  gate     A1 frac(R2_real > R2_shuffled) >= 0.75  AND  A2 median dR2 >= 0.02, BOTH models
  primary  R_lex = retention_real / retention_shuffled
  over the cells whose gate PASSES:
     SURVIVES   R_lex >= 0.70 in >= 2 of 3 cells, pair-survival p at the 1/(n_perm+1) floor
     PARTIAL    0.30 <= R_lex < 0.70
     COLLAPSES  R_lex <  0.30 in >= 2 of 3 cells
  if the gate FAILS on >= 2 of 3 cells at every k -> NOT-TESTABLE
  if k values disagree, the LARGEST adequacy-passing k governs.

Emits paper/sections/tab_lextok.tex and then re-reads it, checking every numeric cell
against its receipt (the emit+read-back pattern that caught defects in two other papers).

    python3 code/analysis/lextok_summary.py            # emit + verify + score
    python3 code/analysis/lextok_summary.py --check     # verify only
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "results/cross_model_sae")
OUT = os.path.join(ROOT, "paper/sections/tab_lextok.tex")

CELLS = [("Qwen3-1.7B $\\leftrightarrow$ Gemma2-2B", "qwen3-1.7b__gemma2-2b", "strong"),
         ("Gemma2-9B $\\leftrightarrow$ Mistral-7B", "gemma2-9b__mistral7b", "median"),
         ("Llama-3.2-1B $\\leftrightarrow$ Mistral-7B", "llama3.2-1b__mistral7b", "weak")]
SURVIVE_R, COLLAPSE_R = 0.70, 0.30


def load_all():
    out = []
    for disp, stem, band in CELLS:
        p = os.path.join(RES, "lextok20k_%s.json" % stem)
        if os.path.exists(p):
            out.append((disp, stem, band, json.load(open(p))))
    return out


def governing_arm(d):
    """Largest adequacy-passing k, per the pre-registration."""
    ok = [(int(k), a) for k, a in d["arms"].items() if a["adequacy"]["gate_passed"]]
    return max(ok, key=lambda t: t[0]) if ok else (None, None)


def score(cells):
    rows = []
    for disp, stem, band, d in cells:
        k, arm = governing_arm(d)
        rows.append({"disp": disp, "stem": stem, "band": band, "d": d,
                     "k": k, "arm": arm,
                     "gate_passed": arm is not None,
                     "R_lex": arm["R_lex"] if arm else float("nan")})
    passing = [r for r in rows if r["gate_passed"]]
    if len(passing) < 2:
        verdict = "NOT-TESTABLE"
    else:
        n_s = sum(1 for r in passing if r["R_lex"] >= SURVIVE_R)
        n_c = sum(1 for r in passing if r["R_lex"] < COLLAPSE_R)
        floors = all(r["arm"]["pair_survival_real"]["p"]
                     <= 1.0 / (r["d"]["n_perm"] + 1) + 1e-12 for r in passing)
        verdict = ("SURVIVES" if (n_s >= 2 and floors)
                   else "COLLAPSES" if n_c >= 2 else "PARTIAL")
    return rows, verdict


def design_facts(rows):
    """Numbers about the NUISANCE DESIGN itself, read off the receipts.

    These are what scope the claim: the gate compares real against shuffled, so the size
    of dR2 says nothing on its own about how much variance the design captures, and the
    design is a restricted one (see max_features / evr). Derived, never typed by hand --
    the "+0.27 = 27% of variance" defect this caption now blocks was a hand-typed number.
    """
    ks = sorted({r["k"] for r in rows if r["gate_passed"]})
    kg = max(ks) if ks else None
    evr = [r["arm"]["explained_variance_ratio"] for r in rows if r["gate_passed"]]
    shuf = [r["arm"]["adequacy"][s]["median_r2_shuffled"]
            for r in rows if r["gate_passed"] for s in ("model_a", "model_b")]
    nfeat = [r["d"]["tfidf_max_features"] for r in rows if r["gate_passed"]]
    return {"k": kg, "evr_pct": 100.0 * max(evr) if evr else float("nan"),
            "shuf_med": max(shuf) if shuf else float("nan"),
            "max_features": max(nfeat) if nfeat else 0}


def emit(rows):
    f = design_facts(rows)
    L = ["% AUTO-GENERATED by code/analysis/lextok_summary.py -- DO NOT HAND-EDIT.",
         "% Numbers formatted from results/cross_model_sae/lextok20k_*.json and verified",
         "% by a read-back in that script.",
         "\\begin{table}[h]", "\\centering",
         "\\caption{\\textbf{Does the sharing survive residualizing on a unigram lexical "
         "model?} $20{,}000$ C4 documents, $n_{\\text{perm}}{=}2{,}000$. The mutual-NN pair "
         "set is "
         "frozen on the \\emph{raw} features and the test asks whether \\emph{those} pairs "
         "still co-activate after cross-fitted residualization on a TF-IDF$\\to$SVD$_k$ "
         "design (stopword-stripped \\emph{unigram} TF-IDF over $%s$ terms, truncated "
         "to $k$ SVD components; at $k{=}%d$ those components retain "
         "$%.1f\\%%$ of that design's own variance). \\emph{gate}: the first stage must beat "
         "a row-shuffled design of identical "
         "spectrum (frac.\\ of features with $R^2_{\\text{real}}>R^2_{\\text{shuf}}$, and "
         "median $\\Delta R^2$); an arm failing it is uninterpretable, not reassuring. "
         "\\textbf{The gate is a margin, not an absolute fit}: it requires "
         "$R^2_{\\text{real}}>R^2_{\\text{shuf}}$, \\emph{not} $R^2_{\\text{real}}>0$, and "
         "the shuffled design predicts badly ($R^2_{\\text{shuf}}$ median $%.2f$ at "
         "$k{=}%d$), so $\\Delta R^2$ is much larger than the variance the nuisance model "
         "actually captures --- which is the separate $R^2_{\\text{real}}$ column. "
         "\\emph{ret.}: excess retained relative to raw. $R_{\\text{lex}}=$ "
         "ret.\\ real$/$ret.\\ shuffled is the lexical-specific retention, since projecting "
         "out any $k$-dim subspace costs something. Row shown is the largest "
         "adequacy-passing $k$. Receipts: \\texttt{lextok20k\\_*.json}.}"
         % ("{,}".join([str(f["max_features"])[:-3], str(f["max_features"])[-3:]]),
            f["k"], f["evr_pct"], f["shuf_med"], f["k"]),
         "\\label{tab:lextok}", "\\footnotesize", "\\setlength{\\tabcolsep}{4pt}",
         # The R^2_real column pushed this past \textwidth; \resizebox is the only fix that
         # cannot silently go stale when a future receipt widens a number.
         "\\resizebox{\\textwidth}{!}{%",
         "\\begin{tabular}{llrrrrrrrr}", "\\toprule",
         "Cell & band & $k$ & pairs & gate frac & gate $\\Delta R^2$ & "
         "$R^2_{\\text{real}}$ & ret.\\ real & "
         "ret.\\ shuf & $R_{\\text{lex}}$ \\\\", "\\midrule"]
    for r in rows:
        if not r["gate_passed"]:
            L.append("%s & %s & \\multicolumn{8}{c}{\\emph{adequacy gate failed at every "
                     "$k$ --- uninterpretable}} \\\\" % (r["disp"], r["band"]))
            continue
        a, d = r["arm"], r["d"]
        ga, gb = a["adequacy"]["model_a"], a["adequacy"]["model_b"]
        L.append("%s & %s & $%d$ & $%d$ & $%.2f$/$%.2f$ & $%+.3f$/$%+.3f$ & $%.3f$/$%.3f$ & $%.3f$ & $%.3f$ & $%.3f$ \\\\"
                 % (r["disp"], r["band"], r["k"], d["frozen_pairs"]["n"],
                    ga["frac_real_beats_shuffled"], gb["frac_real_beats_shuffled"],
                    ga["median_delta_r2"], gb["median_delta_r2"],
                    ga["median_r2_real"], gb["median_r2_real"],
                    a["retention_real"], a["retention_shuffled"], a["R_lex"]))
    L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    open(OUT, "w").write("\n".join(L) + "\n")


def verify(rows):
    if not os.path.exists(OUT):
        print("MISSING %s" % OUT)
        return False
    txt = open(OUT).read()
    bad = []
    for r in rows:
        if not r["gate_passed"]:
            continue
        a, d = r["arm"], r["d"]
        ga, gb = a["adequacy"]["model_a"], a["adequacy"]["model_b"]
        want = ("%s & %s & $%d$ & $%d$ & $%.2f$/$%.2f$ & $%+.3f$/$%+.3f$ & $%.3f$/$%.3f$ & $%.3f$ & $%.3f$ & $%.3f$"
                % (r["disp"], r["band"], r["k"], d["frozen_pairs"]["n"],
                   ga["frac_real_beats_shuffled"], gb["frac_real_beats_shuffled"],
                   ga["median_delta_r2"], gb["median_delta_r2"],
                   ga["median_r2_real"], gb["median_r2_real"],
                   a["retention_real"], a["retention_shuffled"], a["R_lex"]))
        if want not in txt:
            bad.append("%s: emitted row does not match receipt" % r["stem"])
    for b in bad:
        print("MISMATCH  " + b)
    print("read-back: %d row(s) checked, %d mismatches" % (len(rows), len(bad)))
    return not bad


def main():
    cells = load_all()
    if not cells:
        print("no lextok20k_*.json receipts yet")
        return 1
    rows, verdict = score(cells)

    for disp, stem, band, d in cells:
        print("\n== %s (%s)  N=%d docs, %d frozen pairs, n_perm=%d"
              % (stem, band, d["N_docs"], d["frozen_pairs"]["n"], d["n_perm"]))
        print("   raw pair excess=%+.5f z=%.1f p=%.4f"
              % (d["raw"]["excess"], d["raw"]["z"], d["raw"]["p"]))
        for k in sorted(d["arms"], key=int):
            a = d["arms"][k]
            ga, gb = a["adequacy"]["model_a"], a["adequacy"]["model_b"]
            print("   k=%-5s gate %s  A frac=%.2f dR2=%+.3f | B frac=%.2f dR2=%+.3f"
                  % (k, "PASS" if a["adequacy"]["gate_passed"] else "FAIL",
                     ga["frac_real_beats_shuffled"], ga["median_delta_r2"],
                     gb["frac_real_beats_shuffled"], gb["median_delta_r2"]))
            print("          ret_real=%.3f ret_shuf=%.3f R_lex=%.3f | real p=%.4f z=%.1f"
                  % (a["retention_real"], a["retention_shuffled"], a["R_lex"],
                     a["pair_survival_real"]["p"], a["pair_survival_real"]["z"]))

    if "--check" not in sys.argv:
        emit(rows)
        print("\nwrote %s" % os.path.relpath(OUT, ROOT))
    ok = verify(rows)

    print("\n---- pre-registered rule (6848d4c) ----")
    for r in rows:
        print("  %-24s gate=%s  governing k=%s  R_lex=%s"
              % (r["stem"], "PASS" if r["gate_passed"] else "FAIL", r["k"],
                 ("%.3f" % r["R_lex"]) if r["gate_passed"] else "n/a"))
    print("  VERDICT: %s" % verdict)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
