#!/usr/bin/env python3
"""Emit paper/sections/tab_tokalign.tex FROM the tokalign20k receipts, then RE-READ the
emitted file and re-parse every numeric cell against the receipt it came from (the
emit_covctl_table.py anti-drift discipline: numbers are emitted, never hand-typed).

Exit 1 on any mismatch. --selftest plants a perturbed cell in a temp copy and requires
the verifier to catch it.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "results/cross_model_sae")
OUT = os.path.join(ROOT, "paper/sections/tab_tokalign.tex")

CELLS = [
    ("qwen3-1.7b__gemma2-2b", "Qwen3-1.7B$\\leftrightarrow$Gemma-2-2B", "strong"),
    ("gemma2-9b__mistral7b", "Gemma-2-9B$\\leftrightarrow$Mistral-7B", "median"),
    ("llama3.2-1b__mistral7b", "Llama-3.2-1B$\\leftrightarrow$Mistral-7B", "weak"),
]


def load():
    rows = []
    for tag, label, strength in CELLS:
        d = json.load(open(os.path.join(RES, f"tokalign20k_{tag}.json")))
        assert not d.get("smoke"), f"{tag}: refusing to emit a table from a smoke receipt"
        c = json.load(open(os.path.join(RES, f"tokaclean20k_{tag}.json")))
        assert not c.get("smoke"), f"{tag}: refusing to emit a table from a smoke clean receipt"
        assert all(c["a3_requirements"].values()), \
            f"{tag}: clean receipt missing an A3 requirement marker"
        assert all(c["a4_requirements"].values()), \
            f"{tag}: clean receipt missing an A4 requirement marker"
        g0 = d["gates"]["G0"]
        rows.append({
            "tag": tag, "label": label, "strength": strength,
            "pairs": f"{g0['n_recovered_pairs']}/{g0['n_frozen_pairs']}",
            "s1": d["s1"]["obs_mean_pair_r"],
            "s2": d["s2"]["obs_mean_pair_r"],
            "rtok": d["s2"]["R_tok"],
            "s1_clean": c["s1"]["excess"],
            "rtok_clean": c["s2_clean"]["R_tok_clean"],
            "n_scored_clean": c["common_mask"]["n_pairs_scored"],
            "s2c": d["s2c"]["excess"],
            "bigram": d["bigram"]["excess"],
            "p1": d["s1"]["null_n1"]["p"], "p2": d["s2"]["null_n3"]["p"],
            "p3c": c["s2_clean"]["null_n3"]["p"],
            "n_perm": d["n_perm"], "n_perm_clean": c["n_perm"],
        })
    return rows


def emit(rows, path):
    n_scored = "/".join(str(r["n_scored_clean"]) for r in rows)
    lines = [
        "% AUTO-GENERATED by code/analysis/emit_tokalign_table.py -- do not edit by hand.",
        "% Every numeric cell is re-parsed against the receipts after emission.",
        "\\begin{table}[h]", "\\centering",
        "\\caption{\\textbf{Token-aligned sharing ($S_1$) and current-word conditioning "
        "arms ($S_2$; the leakage-clean $R_{\\text{tok}}^{\\text{clean}}$ is the "
        "verdict-bearing arm)} (pre-registered; "
        "$20{,}000$ C4 documents, ${\\approx}9.4\\times10^{5}$ aligned word occurrences "
        "per cell, $n_{\\text{perm}}{=}2{,}000$). \\emph{pairs}: frozen mutual-NN pairs "
        "recovered by the pooled-reconstruction gate G0 (column match $r\\ge0.999$). "
        "$S_1$: mean frozen-pair correlation of within-document-centered word-level "
        "activations (a quantity no document-pooled statistic can contain); its "
        "within-document order-shuffle null N1 has mean ${\\approx}0$, sd "
        "$\\le6\\times10^{-4}$. $S_2$: the same after fixed effects over lowercased, "
        "punctuation-stripped word types with $\\ge20$ occurrences, against a within-type "
        "derangement null N3 (first design: reported, not verdict-bearing --- "
        "selection-leakage caveat, \\Cref{app:tokalign}). "
        "$R_{\\text{tok}}$: support-matched ratio of the $S_2$ excess to the $S_1$ excess "
        "on the same retained occurrences (first design; scored-pair sets are "
        "per-transformation, no common mask asserted). $R_{\\text{tok}}^{\\text{clean}}$: "
        "the same ratio under the registered leakage-clean rerun (amendments A3-EXEC$+$A4: pair "
        "selection and evaluation on disjoint $10{,}000$-document halves with the candidate "
        "universe re-screened on the selection half over the full dictionary; a gated token "
        "stream with a per-cell aliasing audit ($0/1/0$ affected occurrences); converged joint "
        "document$+$type fixed effects re-applied under every null draw; one asserted "
        f"common scored-pair mask, $n_{{\\text{{scored}}}}{{=}}{n_scored}$). "
        "$S_1^{\\text{clean}}$: the S1 excess under that same design (the verdict-bearing "
        "S1). Both "
        "$p_{\\text{N3}}$ at the floor; receipts \\texttt{tokaclean20k\\_*.json}. "
        "$S_2^{c}$: within-document centering \\emph{then} type "
        "demeaning (excess; the projections do not commute). \\emph{bigram}: excess after "
        "demeaning within "
        "(preceding-word-type, word-type) cells. Every primary $p$ at the $1/2001$ floor; "
        "sensitivity arms ($S_2^{c}$, bigram) at their $1/501$ floor.}",
        "\\label{tab:tokalign}", "\\footnotesize\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{llrrrrrrrr}", "\\toprule",
        "Cell & band & pairs & $S_1$ & $S_1^{\\text{clean}}$ & $S_2$ & $R_{\\text{tok}}$ & "
        "$R_{\\text{tok}}^{\\text{clean}}$ & $S_2^{c}$ & bigram \\\\",
        "\\midrule",
    ]
    for r in rows:
        lines.append(
            f"{r['label']} & {r['strength']} & ${r['pairs']}$ & ${r['s1']:.3f}$ & "
            f"${r['s1_clean']:.3f}$ & "
            f"${r['s2']:.3f}$ & ${r['rtok']:.2f}$ & ${r['rtok_clean']:.3f}$ & "
            f"$+{r['s2c']:.3f}$ & $+{r['bigram']:.3f}$ \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


def verify(rows, path):
    """Re-read the emitted file; every numeric cell must re-derive from the receipts."""
    txt = open(path).read()
    bad = []
    for r in rows:
        row_re = re.escape(r["label"]) + r" & \w+ & \$([\d/]+)\$ & \$([\d.]+)\$ & " \
                 r"\$([\d.]+)\$ & " \
                 r"\$([\d.]+)\$ & \$([\d.]+)\$ & \$([\d.]+)\$ & \$\+([\d.]+)\$ & " \
                 r"\$\+([\d.]+)\$"
        m = re.search(row_re, txt)
        if not m:
            bad.append(f"{r['tag']}: row not found in emitted table")
            continue
        want = [r["pairs"], f"{r['s1']:.3f}", f"{r['s1_clean']:.3f}", f"{r['s2']:.3f}",
                f"{r['rtok']:.2f}",
                f"{r['rtok_clean']:.3f}", f"{r['s2c']:.3f}", f"{r['bigram']:.3f}"]
        got = list(m.groups())
        for w, g, name in zip(want, got,
                              ("pairs", "S1", "S1_clean", "S2", "R_tok", "R_tok_clean",
                               "S2c", "bigram")):
            if w != g:
                bad.append(f"{r['tag']} {name}: emitted {g} != receipt {w}")
        floor = 1.0 / (r["n_perm"] + 1)
        for pname in ("p1", "p2"):
            if r[pname] > floor * 1.001:
                bad.append(f"{r['tag']} {pname}={r[pname]} not at the floor the caption "
                           f"asserts ({floor:.6f})")
        floor_clean = 1.0 / (r["n_perm_clean"] + 1)
        if r["p3c"] > floor_clean * 1.001:
            bad.append(f"{r['tag']} p3c={r['p3c']} not at the floor the caption "
                       f"asserts ({floor_clean:.6f})")
    n_scored = "/".join(str(r["n_scored_clean"]) for r in rows)
    if f"{{=}}{n_scored}$" not in txt:
        bad.append(f"caption n_scored triple {n_scored} not found in emitted table")
    return bad


def selftest():
    import tempfile
    rows = load()
    with tempfile.NamedTemporaryFile("w", suffix=".tex", delete=False) as f:
        tmp = f.name
    emit(rows, tmp)
    ok_clean = not verify(rows, tmp)
    txt = open(tmp).read()
    first_s1 = f"{rows[0]['s1']:.3f}"
    open(tmp, "w").write(txt.replace(f"${first_s1}$", "$0.111$", 1))
    caught = bool(verify(rows, tmp))
    emit(rows, tmp)
    txt = open(tmp).read()
    first_rtc = f"{rows[0]['rtok_clean']:.3f}"
    open(tmp, "w").write(txt.replace(f"${first_rtc}$", "$0.222$", 1))
    caught_rtc = bool(verify(rows, tmp))
    os.unlink(tmp)
    print(f"[selftest] clean emit verifies: {ok_clean}; planted 0.111 caught: {caught}; "
          f"planted 0.222 in R_tok_clean caught: {caught_rtc}")
    return 0 if (ok_clean and caught and caught_rtc) else 1


def main():
    if "--selftest" in sys.argv:
        sys.exit(selftest())
    rows = load()
    emit(rows, OUT)
    bad = verify(rows, OUT)
    if bad:
        for b in bad:
            print(f"[MISMATCH] {b}", file=sys.stderr)
        sys.exit(1)
    print(f"[ok] emitted + re-verified {OUT} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
