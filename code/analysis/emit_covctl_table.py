#!/usr/bin/env python3
"""Emit paper/sections/tab_covctl.tex from the covctl receipts, then RE-READ and verify it.

Two project rules are enforced here:
  1. No number in this table is hand-typed. Every cell is formatted from the JSON receipts.
  2. The script does not assert success. After writing, it re-reads the file it just wrote,
     re-parses every numeric cell, and checks each against the receipt it came from. If any
     cell fails to round-trip, the file is left in place for inspection and the script exits
     non-zero. "Wrote the table" is not evidence the table is right.

Also computes the Bonferroni check for the permutation-floor claim, so the multiplicity
statement in the paper is derived rather than asserted.

    python3 code/analysis/emit_covctl_table.py            # emit + verify, exit 1 on mismatch
    python3 code/analysis/emit_covctl_table.py --check    # verify only, do not rewrite
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "results/cross_model_sae")
OUT = os.path.join(ROOT, "paper/sections/tab_covctl.tex")

# display name -> receipt stem. Ordered strong -> median -> weak by baseline C4 z.
CELLS = [
    ("Qwen3-1.7B $\\leftrightarrow$ Gemma2-2B", "qwen3-1.7b__gemma2-2b", "strong"),
    ("Gemma2-9B $\\leftrightarrow$ Mistral-7B", "gemma2-9b__mistral7b", "median"),
    ("Llama-3.2-1B $\\leftrightarrow$ Mistral-7B", "llama3.2-1b__mistral7b", "weak"),
]
KS = [200, 500]
# the multiplicity families the paper's floor claim has to clear
FAMILIES = {"13-cell C4 roster (tab:c4_counts)": 13,
            "17 cells incl. the four GPT-2 cells (tab:gpt2_c4)": 17}


def load(stem, k):
    return json.load(open(os.path.join(RES, "covctl_k%d_c4_%s.json" % (k, stem))))


def rows():
    out = []
    for disp, stem, band in CELLS:
        for k in KS:
            d = load(stem, k)
            b, w, c = d["baseline_random"], d["bow_matched"], d["bow_size_matched_random"]
            out.append(dict(
                disp=disp, stem=stem, band=band, k=k,
                blk=d["mean_bow_block_size"],
                base=b["mutual_excess"], bow=w["mutual_excess"], rnd=c["mutual_excess"],
                raw=w["mutual_excess"] / b["mutual_excess"],
                R=w["mutual_excess"] / c["mutual_excess"],
                p=w["mutual_p"], n_perm=d["n_perm"],
            ))
    return out


def bonferroni():
    lines, ok = [], True
    floor = None
    for r in rows():
        floor = 1.0 / (r["n_perm"] + 1)
        break
    for name, m in FAMILIES.items():
        thresh = 0.05 / m
        good = floor < thresh
        ok &= good
        lines.append("  floor %.6f %s Bonferroni %.6f (0.05/%d, %s) -> %s"
                     % (floor, "<" if good else ">=", thresh, m, name,
                        "CLEARS" if good else "FAILS"))
    return floor, ok, lines


def emit():
    rr = rows()
    L = []
    L.append("% AUTO-GENERATED by code/analysis/emit_covctl_table.py -- DO NOT HAND-EDIT.")
    L.append("% Every number is formatted from results/cross_model_sae/covctl_k*_c4_*.json")
    L.append("% and verified by a read-back in that script. Re-run it after any new receipt.")
    L.append("\\begin{table}[h]")
    L.append("\\centering")
    L.append("\\caption{\\textbf{Fine-grained lexical/topic-matched null.} Mutual-NN excess "
             "(observed $-$ null mean) on three representative C4-robust cells under a "
             "permutation restricted to $k$-way TF-IDF/KMeans topic strata, "
             "$n_{\\text{perm}}{=}2{,}000$. \\emph{base}: unrestricted null. \\emph{bow}: "
             "topic-matched. \\emph{size-rnd}: strata with the \\emph{same block sizes} but "
             "random membership, so they carry no lexical information --- this calibrates the "
             "mechanical shrinkage that any fine partition induces (permuting inside small "
             "blocks approaches the identity; at block size $1$ the excess is $0$ by "
             "construction). $R=\\text{bow}/\\text{size-rnd}$ is therefore the "
             "\\emph{lexical-specific} retention; the raw bow$/$base ratio is shown for "
             "completeness but is confounded by that shrinkage. Receipts: "
             "\\texttt{covctl\\_k*\\_c4\\_*.json}.}")
    L.append("\\label{tab:covctl}")
    L.append("\\footnotesize")
    L.append("\\setlength{\\tabcolsep}{4pt}")
    L.append("\\begin{tabular}{llrrrrrr}")
    L.append("\\toprule")
    L.append("Cell & band & $k$ & blk & base & bow & size-rnd & $R$ \\\\")
    L.append("\\midrule")
    prev = None
    for r in rr:
        if prev is not None and r["stem"] != prev:
            L.append("\\midrule")
        prev = r["stem"]
        L.append("%s & %s & $%d$ & $%.0f$ & $%+.1f$ & $%+.1f$ & $%+.1f$ & $%.3f$ \\\\"
                 % (r["disp"], r["band"], r["k"], r["blk"], r["base"], r["bow"],
                    r["rnd"], r["R"]))
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    L.append("\\end{table}")
    open(OUT, "w").write("\n".join(L) + "\n")
    return rr


def verify(rr):
    """Re-read the emitted file and check every numeric cell against its receipt."""
    if not os.path.exists(OUT):
        print("MISSING %s" % OUT)
        return False
    txt = open(OUT).read()
    bad = []
    for r in rr:
        pat = (re.escape(r["disp"]) + r"\s*&\s*" + r["band"] + r"\s*&\s*\$" + str(r["k"])
               + r"\$\s*&\s*\$(-?[\d.]+)\$\s*&\s*\$([+-][\d.]+)\$\s*&\s*\$([+-][\d.]+)\$"
                 r"\s*&\s*\$([+-][\d.]+)\$\s*&\s*\$([\d.]+)\$")
        m = re.search(pat, txt)
        if not m:
            bad.append("%s k=%d: row not found in emitted table" % (r["stem"], r["k"]))
            continue
        got = [float(x) for x in m.groups()]
        want = [round(r["blk"]), round(r["base"], 1), round(r["bow"], 1),
                round(r["rnd"], 1), round(r["R"], 3)]
        for name, g, w in zip(("blk", "base", "bow", "size-rnd", "R"), got, want):
            if abs(g - w) > 1e-9:
                bad.append("%s k=%d %s: table %s, receipt %s" % (r["stem"], r["k"], name, g, w))
    for b in bad:
        print("MISMATCH  " + b)
    print("read-back: %d rows re-parsed, %d mismatches" % (len(rr), len(bad)))
    return not bad


def pdf_text():
    """Text of the COMPILED pdf. Exit code checked: a failed pdftotext returns empty
    stdout, which is indistinguishable from 'number absent' and would turn this gate into
    a rubber stamp."""
    import subprocess
    pdf = os.path.join(ROOT, "paper/main.pdf")
    if not os.path.exists(pdf):
        raise RuntimeError("no paper/main.pdf")
    r = subprocess.run(["pdftotext", "-layout", pdf, "-"],
                       capture_output=True, text=True, timeout=120)
    if r.returncode != 0:
        raise RuntimeError("pdftotext exit=%d" % r.returncode)
    return r.stdout


def check_pdf(rr, planted=None):
    """Verify the emitted numbers actually reached the COMPILED PDF.

    Verifying the .tex fragment proves only that the right bytes were written to a file
    LaTeX may or may not include, may include stale via an old .aux, or may typeset into a
    float that got dropped. The reader sees the PDF, so the PDF is what must be gated --
    this is the emitter half of the same scope gap that let a sibling project's withdrawn claim
    survive in a figure while its guard reported PASS.

    `planted` injects a value that must NOT be present, proving the check can fail.
    """
    txt = pdf_text()
    bad = []
    checked = 0
    for r in rr:
        for name, val in (("base", "%+.1f" % r["base"]), ("bow", "%+.1f" % r["bow"]),
                          ("size-rnd", "%+.1f" % r["rnd"]), ("R", "%.3f" % r["R"])):
            checked += 1
            # pdftotext renders the LaTeX minus sign as U+2212; normalise both ways
            cands = {val, val.replace("-", "−"), val.lstrip("+"),
                     val.lstrip("+").replace("-", "−")}
            if not any(c in txt for c in cands):
                bad.append("%s k=%d %s=%s not found in compiled PDF"
                           % (r["stem"], r["k"], name, val))
    if planted is not None:
        checked += 1
        if planted in txt:
            bad.append("PLANT %s unexpectedly present -- plant is not a valid negative"
                       % planted)
    for b in bad:
        print("PDF MISMATCH  " + b)
    print("pdf: %d emitted value(s) checked against the compiled PDF, %d missing"
          % (checked, len(bad)))
    return not bad


def selftest_pdf(rr):
    """The PDF gate must be able to FAIL. Perturb every emitted value and require that the
    perturbed values are absent from the PDF; if a perturbed value were 'found', the check
    would be matching noise rather than the table."""
    txt = pdf_text()
    spurious = []
    for r in rr:
        for val in ("%+.1f" % (r["base"] + 111.1), "%.3f" % (r["R"] + 0.111)):
            cands = {val, val.replace("-", "−"), val.lstrip("+")}
            if any(c in txt for c in cands):
                spurious.append("%s k=%d perturbed %s WAS found -> gate matches noise"
                                % (r["stem"], r["k"], val))
    for s in spurious:
        print("SELFTEST  " + s)
    ok = not spurious
    print("pdf selftest: %d perturbed value(s) checked, %d spurious hits -> gate %s"
          % (2 * len(rr), len(spurious), "CAN FAIL" if ok else "IS DECORATIVE"))
    return ok


def check_prose(rr):
    """Gate the numbers hand-typed into the PROSE (not the table) against the receipts.

    another project shipped two hand-typed numbers this week and both were wrong, one of them
    inverting a conclusion. Any receipt-derived figure that appears in running text is
    checked here, so prose cannot drift from the table it describes.
    """
    app = open(os.path.join(ROOT, "paper/sections/appendix.tex")).read()
    Rs = [r["R"] for r in rr]
    lo, hi = min(Rs), max(Rs)
    qwen500 = next(r for r in rr if r["stem"] == "qwen3-1.7b__gemma2-2b" and r["k"] == 500)
    blk = {r["k"]: r["blk"] for r in rr}
    floor = 1.0 / (rr[0]["n_perm"] + 1)

    # plain substring checks against the LaTeX source (not regex): '$' is literal.
    want = [
        # 2026-09-25: the limitations sentence quoting this range was removed (it duplicated
        # tab:ladder and is not a limitation); the appendix copy below carries the lower bound.
        # The old needle had already been failing since the 09-24 overhaul reformatted it to 3 dp.
        ("appendix R lower bound", app,
         "leaves at least $%d\\%%$ of the excess" % (int(round(lo * 1000)) // 10)),
        ("appendix R range", app, "$%.2f$--$%.2f$ across all six" % (lo, hi)),
        ("appendix raw ratio (qwen k=500)", app,
         "to $%.2f$ for the strongest cell" % qwen500["raw"]),
        ("appendix size-rnd vs bow (qwen k=500)", app,
         "($%+.1f$ vs.\\ $%+.1f$" % (qwen500["rnd"], qwen500["bow"])),
        ("appendix block size k=200", app, "the mean block is $%d$ documents" % round(blk[200])),
        ("appendix block size k=500", app, "at $k{=}500$ it is $%d$" % round(blk[500])),
        ("appendix perm floor", app, "$1/%d$ floor" % (rr[0]["n_perm"] + 1)),
        ("appendix bonferroni 13", app, "$0.05/13=%.4f$" % (0.05 / 13)),
        ("appendix bonferroni 17", app, "$0.05/17=%.4f$" % (0.05 / 17)),
        # "appendix floor value" ($1/2001{=}0.0005$) retired 2026-09-25: that literal left the
        # appendix in f3e5228; the floor itself is still pinned by "appendix perm floor" above.
    ]
    bad = [name for name, hay, needle in want if needle not in hay]
    for name, hay, needle in want:
        if needle not in hay:
            print("PROSE MISMATCH  %s: expected literal %r not found" % (name, needle))
    print("prose: %d receipt-derived figures checked, %d mismatches" % (len(want), len(bad)))
    return not bad


def main():
    check_only = "--check" in sys.argv
    rr = rows() if check_only else emit()
    if not check_only:
        print("wrote %s" % os.path.relpath(OUT, ROOT))
    ok = verify(rr)

    floor, bonf_ok, lines = bonferroni()
    print("\nmultiplicity (permutation floor at n_perm=%d):" % rr[0]["n_perm"])
    for l in lines:
        print(l)

    Rs = [r["R"] for r in rr]
    n_surv = sum(1 for r in rr if r["R"] >= 0.70)
    n_fail = sum(1 for r in rr if r["R"] < 0.30)
    print("\npre-registered rule: R range %.3f--%.3f over %d cell-by-k results; "
          "%d >= 0.70, %d < 0.30" % (min(Rs), max(Rs), len(rr), n_surv, n_fail))
    print("VERDICT: %s" % ("SURVIVES" if n_surv == len(rr) else
                           "FAILS" if n_fail >= 2 else "PARTIAL"))
    print()
    prose_ok = check_prose(rr)
    try:
        pdf_ok = check_pdf(rr)
        if "--selftest" in sys.argv:
            pdf_ok = selftest_pdf(rr) and pdf_ok
    except Exception as e:
        print("PDF SCOPE UNAVAILABLE: %s -- treating as FAILURE, not as clean" % e)
        pdf_ok = False
    findings = sum(0 if x else 1 for x in (ok, bonf_ok, prose_ok, pdf_ok))
    print("FINDINGS=%d" % findings)
    return 0 if findings == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
