#!/usr/bin/env python3
"""Emit paper/sections/tab_ninecell.tex (App. ninecell, revision R1) from the cluster nine-cell
receipts, WITHOUT any bootstrap interval.

Why this file exists (2026-10-07, revision R1, item C1/C2). The submitted Table 14 was the
`summarize` output of ninecell_strengthen_20260926.py on the five-cell local fallback and printed
document-bootstrap intervals for Delta_E. The registered post-submission diagnosis
(notes/PREREG_F1_bootstrap_diagnosis_20261004.md, receipt results/f1_bootstrap_diag_20261004/
F1_BOOTSTRAP_DIAG.json) found that bootstrap invalid here (Q-C reading C0), so R1 reports no
interval. `summarize` cannot be reused as is: it always prints the intervals it finds and it
rewrites NINECELL_SUMMARY.json inside the receipt directory. This emitter is read-only on the
receipts, standard library only, and formats the same fields `summarize` formats (obs_M,
point.len.R, point.top10.R, consecutive.held_out.excess, random_splits.min/max_excess,
random_splits.median_r) plus random_splits.rho, in the registered CELLS order.

    /usr/bin/python3 code/analysis/emit_ninecell_table.py            # write the table
    /usr/bin/python3 code/analysis/emit_ninecell_table.py --check    # byte-compare, exit 1 on drift
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RECEIPTS = ROOT / "results/ninecell_20260926/cluster_18577359"
OUT = ROOT / "paper/sections/tab_ninecell.tex"
CELLS = ["qwen3-1.7b__gemma2-2b", "qwen3-1.7b__gemma2-9b", "qwen3-1.7b__mistral7b",
         "qwen3-8b__gemma2-2b", "qwen3-8b__gemma2-9b", "qwen3-8b__mistral7b",
         "gemma2-2b__mistral7b", "gemma2-9b__mistral7b", "llama3.2-1b__mistral7b"]
LAB = {"qwen3-1.7b": "Q1.7", "qwen3-8b": "Q8", "gemma2-2b": "G2", "gemma2-9b": "G9",
       "mistral7b": "M", "llama3.2-1b": "L1"}


def f3(x):
    return f"{x:.3f}"


def render():
    lines = ["% AUTO-GENERATED by code/analysis/emit_ninecell_table.py -- DO NOT HAND-EDIT.",
             "% Source: results/ninecell_20260926/cluster_18577359/{A,B}_<cell>.json (cluster run, after",
             "% submission); no bootstrap interval is printed (withdrawn, results/f1_bootstrap_diag_20261004/).",
             "\\begin{tabular}{@{}lrrrrrrr@{}}", "\\toprule",
             "Cell & $M$ & $R_{\\text{len}}$ & $R_{\\text{top}}$ ($k{=}10$) & $\\Delta_E$ & "
             "random split $\\Delta_E$ & $\\rho$ & median $r$ \\\\", "\\midrule"]
    for c in CELLS:
        a = json.loads((RECEIPTS / f"A_{c}.json").read_text())
        b = json.loads((RECEIPTS / f"B_{c}.json").read_text())
        assert a["cell"] == b["cell"] == c, c
        pt, rs = a["point"], b["random_splits"]
        A_, B_ = c.split("__")
        lines.append(f"{LAB[A_]}--{LAB[B_]} & ${a['obs_M']}$ & ${f3(pt['len']['R'])}$ & "
                     f"${f3(pt['top10']['R'])}$ & ${f3(b['consecutive']['held_out']['excess'])}$ & "
                     f"${f3(rs['min_excess'])}$--${f3(rs['max_excess'])}$ & ${f3(rs['rho'])}$ & "
                     f"${f3(rs['median_r'])}$ \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("emit_ninecell_table --check:", "PASS" if ok else f"FAIL ({OUT.relative_to(ROOT)} differs "
              "from the receipts; re-run without --check, never hand-edit)")
        return 0 if ok else 1
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
